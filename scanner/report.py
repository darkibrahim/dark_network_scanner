def to_html(data: dict) -> str:
    sections = []
    for host in data["hosts"]:
        status_class = "alive" if host["alive"] else "down"
        status_text = "UP" if host["alive"] else "DOWN"
        port_rows = "".join(
            f"<tr><td class='port-open'>{p['port']}</td><td>{p['service']}</td>"
            f"<td>{(p['banner'] or '').replace('<', '&lt;')}</td></tr>"
            for p in host["ports"]
        ) or "<tr><td colspan='3'><i>no open ports found</i></td></tr>"
        sections.append(
            f"<h2>{host['host']} "
            f"<span class='{status_class}'>&nbsp;[{status_text}]</span></h2>"
            f"<table><tr><th>Port</th><th>Service</th><th>Banner</th></tr>{port_rows}</table>"
        )
    return _HTML_TEMPLATE.format(
        target=data["target"], generated_at=data["generated_at"], rows="\n".join(sections)
    )
