"""Output formatting: text (terminal), JSON, CSV, and a Premium HTML report."""
from __future__ import annotations

import csv
import io
import json
from datetime import datetime, timezone

from .discovery import HostStatus
from .portscan import PortResult


def results_to_dict(target: str, hosts: list[HostStatus], ports: dict[str, list[PortResult]]) -> dict:
    return {
        "target": target,
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "hosts": [
            {
                "host": h.host,
                "alive": h.alive,
                "method": h.method,
                "ports": [
                    {"port": p.port, "open": p.open, "service": p.service, "banner": p.banner}
                    for p in ports.get(h.host, [])
                    if p.open
                ],
            }
            for h in hosts
        ],
    }


def to_json(data: dict, indent: int = 2) -> str:
    return json.dumps(data, indent=indent)


def to_csv(data: dict) -> str:
    buf = io.StringIO()
    writer = csv.writer(buf)
    writer.writerow(["host", "alive", "method", "port", "service", "banner"])
    for host in data["hosts"]:
        if not host["ports"]:
            writer.writerow([host["host"], host["alive"], host["method"], "", "", ""])
        for p in host["ports"]:
            writer.writerow([host["host"], host["alive"], host["method"], p["port"], p["service"], p["banner"] or ""])
    return buf.getvalue()


